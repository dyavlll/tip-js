const result1 = "8" + 2;
console.log("\"8\" + 2", result1, typeof result1);
const result2 = "8" - 2;
console.log("\"8\" - 2", result2, typeof result2);
const result3 = Number("8") + 2;
console.log("Number(\"8\") + 2", result3, typeof result3);
const result4 = "12" > "3";
console.log("\"12\" > \"3\"", result4, typeof result4);
const result5 = 12 === "12";
console.log("12 === \"12\"", result5, typeof result5);
const result6 = Number("");
console.log("Number(\"\")", result6, typeof result6);
const result7 = Number("text");
console.log("Number(\"text\")", result7, typeof result7);
const result8 = Boolean("false");
console.log("Boolean(\"false\")", result8, typeof result8);
